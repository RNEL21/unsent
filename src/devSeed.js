export function seedIfRequested() {
  if (!import.meta.env.DEV) return
  const params = new URLSearchParams(window.location.search)
  if (!params.has('seed')) return

  const now = Date.now()
  const day = 24 * 60 * 60 * 1000
  const entries = DEMO.map(([to, text, daysAgo, note], i) => {
    const createdAt = now - daysAgo * day - i * 3600 * 1000
    return {
      id: crypto.randomUUID(),
      to,
      text,
      createdAt,
      monthKey: monthKeyOf(createdAt),
      note,
    }
  })
  useArchiveStore.setState({ entries })
}
